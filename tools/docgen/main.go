// Command docgen writes the configuration reference to docs/config.reference.yaml, a YAML file of
// every configuration key. The comment above each key comes from the doc comment of its field in
// package config, and its default and allowed values from the field's jsonschema struct tag.
package main

//go:generate go run .

import (
	"bytes"
	"fmt"
	"os"
	"reflect"
	"strings"
	"time"

	"github.com/invopop/jsonschema"
	"go.uber.org/zap/zapcore"
	"go.yaml.in/yaml/v4"

	"gateway/internal/config"
	yamlutil "gateway/internal/util/yaml"
)

// outputPath is relative to this package's directory, where go generate runs.
const outputPath = "../../docs/config.reference.yaml"

const header = `# Code generated by tools/docgen. DO NOT EDIT.
#
# Reference for the Gateway configuration file. Each key is shown with its default value, or with
# an empty value when it has no default. Some keys are mutually exclusive, such as ssh.ca.local and
# ssh.ca.vault, so this file cannot be used as a configuration as is.

`

// commentWidth is the column at which comments are wrapped.
const commentWidth = 100

const (
	typeString = "string"
	typeArray  = "array"
	typeObject = "object"
)

func main() {
	doc, err := render()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	if err := os.WriteFile(outputPath, doc, 0o600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render() ([]byte, error) {
	schema, err := reflectSchema()
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer

	b.WriteString(header)
	writeObject(&b, schema, "", "")

	// Every key and value must parse as the configuration, so that a key renamed in package config or
	// a value that does not decode fails the generation.
	decoder := yaml.NewDecoder(bytes.NewReader(b.Bytes()))
	decoder.KnownFields(true)

	if err := decoder.Decode(&config.Config{}); err != nil {
		return nil, fmt.Errorf("generated reference does not parse as the configuration: %w", err)
	}

	return b.Bytes(), nil
}

func reflectSchema() (*jsonschema.Schema, error) {
	r := &jsonschema.Reflector{
		FieldNameTag:   "yaml",
		DoNotReference: true,
		Mapper:         mapType,
	}

	// Comments are keyed by import path, which AddGoComments derives by joining the base with
	// each parsed file's directory, so "../../internal/config" from this package resolves to
	// package config.
	if err := r.AddGoComments("gateway/tools/docgen", "../../internal/config", jsonschema.WithFullComment()); err != nil {
		return nil, fmt.Errorf("failed to parse config comments: %w", err)
	}

	r.LookupComment = lookupComment(r.CommentMap)

	return r.Reflect(&config.Config{}), nil
}

// lookupComment returns a Reflector.LookupComment that describes a field by its doc comment, or by
// its type's doc comment when the field has none. The Reflector itself drops type comments of
// fields, since it overwrites them with the field's empty jsonschema_description tag. An empty name
// asks for the comment of t itself, which t may not be a struct for, and no key is written with it.
func lookupComment(comments map[string]string) func(reflect.Type, string) string {
	return func(t reflect.Type, name string) string {
		if name == "" {
			return ""
		}

		if comment := comments[typeName(t)+"."+name]; comment != "" {
			return trimName(comment, name)
		}

		field, ok := t.FieldByName(name)
		if !ok {
			return ""
		}

		return typeComment(comments, field.Type)
	}
}

// typeComment returns the doc comment of t, or of the element type of a pointer, slice or map.
func typeComment(comments map[string]string, t reflect.Type) string {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
		t = t.Elem()
	}

	return trimName(comments[typeName(t)], t.Name())
}

func typeName(t reflect.Type) string {
	return t.PkgPath() + "." + t.Name()
}

// trimName removes the leading name from a Go doc comment, so that "MaxSize is the file size" reads
// as "The file size", and "TLSConfig configures" as "Configures".
func trimName(comment, name string) string {
	rest, ok := strings.CutPrefix(comment, name+" is ")
	if !ok {
		rest, ok = strings.CutPrefix(comment, name+" ")
	}

	if !ok || rest == "" {
		return comment
	}

	return strings.ToUpper(rest[:1]) + rest[1:]
}

// mapType describes the integer types that are written as strings in YAML and parsed by their own
// unmarshalers. The Reflector drops a default that does not parse as the schema's type, so these
// must be strings for defaults such as "5m" to survive.
func mapType(t reflect.Type) *jsonschema.Schema {
	switch t {
	case reflect.TypeFor[time.Duration](), reflect.TypeFor[yamlutil.Duration]():
		return &jsonschema.Schema{Type: typeString, Title: "duration"}
	case reflect.TypeFor[yamlutil.ByteSize]():
		return &jsonschema.Schema{Type: typeString, Title: "byte size"}
	case reflect.TypeFor[zapcore.Level]():
		return &jsonschema.Schema{Type: typeString, Enum: []any{"debug", "info", "warn", "error"}}
	default:
		return nil
	}
}

// writeObject writes the keys of the object schema, each under a comment of its description.
// firstIndent prefixes the first key instead of indent, so that the keys of a list item follow
// its "- ".
func writeObject(b *bytes.Buffer, schema *jsonschema.Schema, firstIndent, indent string) {
	keyIndent := firstIndent

	for pair := schema.Properties.Oldest(); pair != nil; pair = pair.Next() {
		key, prop := pair.Key, pair.Value

		if pair != schema.Properties.Oldest() {
			b.WriteString("\n")
		}

		writeComment(b, indent, comment(prop))
		writeKey(b, key, prop, keyIndent, indent)

		keyIndent = indent
	}
}

// comment returns the lines of the comment above the property's key: its description, its
// allowed values and its default.
func comment(prop *jsonschema.Schema) []string {
	var lines []string

	if prop.Description != "" {
		lines = append(lines, prop.Description)
	}

	if len(prop.Enum) > 0 {
		values := make([]string, len(prop.Enum))
		for i, v := range prop.Enum {
			values[i] = fmt.Sprint(v)
		}

		lines = append(lines, "One of: "+strings.Join(values, ", "))
	}

	if prop.Default != nil {
		lines = append(lines, fmt.Sprintf("Default: %v", prop.Default))
	}

	return lines
}

func writeComment(b *bytes.Buffer, indent string, lines []string) {
	for _, line := range lines {
		for _, wrapped := range wrap(line, commentWidth-len(indent)-len("# ")) {
			fmt.Fprintf(b, "%s# %s\n", indent, wrapped)
		}
	}
}

// wrap splits s into lines of at most width characters, breaking at whitespace. A word longer than
// width gets a line of its own.
func wrap(s string, width int) []string {
	var lines []string

	line := ""

	for word := range strings.FieldsSeq(s) {
		switch {
		case line == "":
			line = word
		case len(line)+1+len(word) <= width:
			line += " " + word
		default:
			lines = append(lines, line)
			line = word
		}
	}

	return append(lines, line)
}

func writeKey(b *bytes.Buffer, key string, prop *jsonschema.Schema, keyIndent, indent string) {
	object := nestedObject(prop)

	switch {
	case object != nil && prop.Type == typeArray:
		fmt.Fprintf(b, "%s%s:\n", keyIndent, key)
		writeObject(b, object, indent+"  - ", indent+"    ")
	case object != nil:
		fmt.Fprintf(b, "%s%s:\n", keyIndent, key)
		writeObject(b, object, indent+"  ", indent+"  ")
	case prop.Type == typeArray:
		fmt.Fprintf(b, "%s%s: []\n", keyIndent, key)
	case prop.Type == typeObject:
		fmt.Fprintf(b, "%s%s: {}\n", keyIndent, key)
	default:
		fmt.Fprintf(b, "%s%s: %s\n", keyIndent, key, value(prop))
	}
}

// nestedObject returns the object schema whose keys are written under the property: the property
// itself, or the items of a list, when it has keys of its own.
func nestedObject(prop *jsonschema.Schema) *jsonschema.Schema {
	if prop.Type == typeArray {
		prop = prop.Items
	}

	if prop.Type == typeObject && prop.Properties != nil && prop.Properties.Len() > 0 {
		return prop
	}

	return nil
}

// value returns the property's default, or the zero value of its type when it has none. A string
// default is quoted only where YAML would read it as another type. Durations and byte sizes, titled
// by mapType, do not parse from an empty string, so their zero value is 0.
func value(prop *jsonschema.Schema) string {
	switch {
	case prop.Type == typeString && prop.Default != nil:
		out, _ := yaml.Marshal(fmt.Sprint(prop.Default))

		return strings.TrimSuffix(string(out), "\n")
	case prop.Default != nil:
		return fmt.Sprint(prop.Default)
	case prop.Type == typeString && prop.Title == "":
		return `""`
	default:
		return "0"
	}
}
